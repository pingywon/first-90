export function icon(name, cls = "") {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  if (cls) svg.setAttribute("class", cls);
  svg.innerHTML = P[name] || "";
  return svg;
}

export function fillIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    if (!el.querySelector("svg")) el.prepend(icon(el.dataset.icon));
  }
}

const store = {
  get: (k) => { try { return localStorage.getItem(k); } catch { return null; } },
  set: (k, v) => { try { localStorage.setItem(k, v); } catch { /* fine without it */ } },
};

export function themeToggle(btn) {
  const root = document.documentElement;
  const saved = store.get("lab:theme");
  if (saved) root.dataset.theme = saved;
  const isDark = () => root.dataset.theme ? root.dataset.theme === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;
  const paint = () => {
    btn.replaceChildren(icon(isDark() ? "sun" : "moon"));
    btn.setAttribute("aria-label", isDark() ? "Light mode" : "Dark mode");
    btn.title = isDark() ? "Light mode" : "Dark mode";
  };
  btn.addEventListener("click", () => {
    root.dataset.theme = isDark() ? "light" : "dark";
    store.set("lab:theme", root.dataset.theme);
    paint();
  });
  paint();
}
